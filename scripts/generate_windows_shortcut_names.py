#!/usr/bin/env python3
"""Generate the Windows installer's localized shortcut cleanup list.

The app can create a shortcut in any language it ships, but Inno Setup only
offers 32 of those languages. Setup still has to be able to remove a shortcut
the app created under a name Setup's own [Languages] list could never produce,
so the exact names are compiled into the installer from the same catalogs the
app uses.

Run from the repository root:

    .venv-build/Scripts/python.exe scripts/generate_windows_shortcut_names.py

``--check`` verifies the committed include is current without writing it.
User-learned catalogs are deliberately ignored; a build must not depend on
what the person running it has opened in the app.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from src import i18n  # noqa: E402
from src import shortcut_manager as sm  # noqa: E402

OUTPUT = ROOT / "scripts" / "build_windows_shortcut_names.iss"


def _pascal_string(value: str) -> str:
    if "\n" in value or "\r" in value:
        raise ValueError(f"shortcut name contains a line break: {value!r}")
    return value.replace("'", "''")


def render() -> str:
    """The complete include file, deterministic across runs and machines."""
    names = sm.app_shortcut_names_for_cleanup(i18n.shipped_catalog_codes())
    lines = [
        "{ Generated by scripts/generate_windows_shortcut_names.py from the app's",
        "  shipped language catalogs. Do not edit by hand. }",
        "procedure AddAppShortcutNames(Names: TStringList);",
        "begin",
    ]
    lines.extend(f"  Names.Add('{_pascal_string(name)}');" for name in names)
    lines.extend(("end;", ""))
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail when the committed include does not match the catalogs",
    )
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        try:
            current = OUTPUT.read_text(encoding="utf-8-sig")
        except FileNotFoundError:
            current = None
        if current != text:
            print(
                f"{OUTPUT.relative_to(ROOT)} is stale; run "
                "scripts/generate_windows_shortcut_names.py",
                file=sys.stderr,
            )
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is current")
        return 0
    OUTPUT.write_text(text, encoding="utf-8-sig", newline="\r\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
