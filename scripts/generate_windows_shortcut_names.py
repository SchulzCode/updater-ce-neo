#!/usr/bin/env python3
"""Generate the Windows installer's shortcut names from the app's catalogs.

The installer and the app have to write the same shortcut file names. The app
names a shortcut after ``app_name`` in the language it is running in, and can
rename one when that language changes; Setup creates its shortcuts from
[CustomMessages]. Hand-written Setup messages drifted from the catalogs, so
both lists are generated here from the same catalogs, through the same function
the app uses.

Two includes come out of this:

* ``build_windows_shortcut_names.iss`` — every app name in any shipped
  language, for deleting shortcuts Setup's own [Languages] list cannot name.
* ``build_windows_installer_names.iss`` — the [CustomMessages] entries Setup
  uses to create the shortcut in the language picked on its first page.

Run from the repository root:

    .venv-build/bin/python scripts/generate_windows_shortcut_names.py

``--check`` verifies both committed includes are current without writing them.
User-learned catalogs are deliberately ignored; a build must not depend on
what the person running it has opened in the app.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from src import i18n  # noqa: E402
from src import shortcut_manager as sm  # noqa: E402

OUTPUT = ROOT / "scripts" / "build_windows_shortcut_names.iss"
MESSAGES = ROOT / "scripts" / "build_windows_installer_names.iss"

# Inno's language files are optional in its installer: a compiler installation
# may omit translations that another version ships. The main script already
# guards its [Languages] entries with FileExists; these guards keep the
# generated [CustomMessages] in step with it instead of failing on a language
# the compiler does not have.
_INNO_LANGUAGE_FILES = {
    "arabic": "Arabic.isl",
    "armenian": "Armenian.isl",
    "brazilianportuguese": "BrazilianPortuguese.isl",
    "bulgarian": "Bulgarian.isl",
    "catalan": "Catalan.isl",
    "chinesesimplified": "ChineseSimplified.isl",
    "chinesetraditional": "ChineseTraditional.isl",
    "corsican": "Corsican.isl",
    "czech": "Czech.isl",
    "danish": "Danish.isl",
    "dutch": "Dutch.isl",
    "finnish": "Finnish.isl",
    "french": "French.isl",
    "german": "German.isl",
    "hebrew": "Hebrew.isl",
    "hungarian": "Hungarian.isl",
    "icelandic": "Icelandic.isl",
    "italian": "Italian.isl",
    "japanese": "Japanese.isl",
    "korean": "Korean.isl",
    "norwegian": "Norwegian.isl",
    "polish": "Polish.isl",
    "portuguese": "Portuguese.isl",
    "russian": "Russian.isl",
    "slovak": "Slovak.isl",
    "slovenian": "Slovenian.isl",
    "spanish": "Spanish.isl",
    "swedish": "Swedish.isl",
    "tamil": "Tamil.isl",
    "turkish": "Turkish.isl",
    "ukrainian": "Ukrainian.isl",
}


def _pascal_string(value: str) -> str:
    if "\n" in value or "\r" in value:
        raise ValueError(f"shortcut name contains a line break: {value!r}")
    return value.replace("'", "''")


def render() -> str:
    """The complete cleanup include, deterministic across runs and machines."""
    names = sm.app_shortcut_names_for_cleanup(i18n.shipped_catalog_codes())
    lines = [
        "{ Generated by scripts/generate_windows_shortcut_names.py from the app's",
        "  shipped language catalogs. Do not edit by hand. }",
        "procedure AddAppShortcutNames(Names: TStringList);",
        "begin",
    ]
    lines.extend(f"  Names.Add('{_pascal_string(name)}');" for name in names)
    lines.extend(("end;", ""))
    return "\n".join(lines)


def render_messages() -> str:
    """The shortcut names Setup creates, per installer language.

    Setup offers fewer languages than the app ships, so each of its languages
    is mapped to the app catalogs it corresponds to. The first app language
    with an actual translation wins, exactly as the app falls back to its base
    language; an English name is left out so Setup's own default applies.
    """
    lines = [
        "; Generated by scripts/generate_windows_shortcut_names.py from the app's",
        "; shipped language catalogs. Do not edit by hand.",
    ]
    for inno_name, codes in sorted(sm.INNO_SHORTCUT_LANGUAGES.items()):
        name = ""
        for code in codes:
            name = sm.shortcut_name_for_language(code)
            if name:
                break
        if not name:
            continue
        isl_name = _INNO_LANGUAGE_FILES[inno_name]
        lines.append(
            f'#if FileExists(AddBackslash(CompilerPath) + "Languages\\{isl_name}")'
        )
        lines.append(f"{inno_name}.AppShortcutName={name}")
        lines.append(f"{inno_name}.DesktopAppShortcutName={name}")
        lines.append("#endif")
    lines.append("")
    return "\n".join(lines)


def _write(path: Path, text: str) -> None:
    path.write_text(text, encoding="utf-8-sig", newline="\r\n")


def _is_current(path: Path, text: str) -> bool:
    try:
        return path.read_text(encoding="utf-8-sig") == text
    except FileNotFoundError:
        return False


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail when a committed include does not match the catalogs",
    )
    args = parser.parse_args(argv)
    stale = []
    for path, text in ((OUTPUT, render()), (MESSAGES, render_messages())):
        if args.check:
            if not _is_current(path, text):
                stale.append(path.relative_to(ROOT))
            continue
        _write(path, text)
        print(f"wrote {path.relative_to(ROOT)}")
    if args.check:
        if stale:
            for path in stale:
                print(
                    f"{path} is stale; run scripts/generate_windows_shortcut_names.py",
                    file=sys.stderr,
                )
            return 1
        print("installer shortcut includes are current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
