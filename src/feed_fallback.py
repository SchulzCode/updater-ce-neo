"""Static feed fallback client for ``innioasis.app``.

When GitHub's API (``api.github.com``) or raw file host is rate-limited,
blocked, or unreachable, Updater CE Neo falls back to the static feeds
generated by GitHub Actions and hosted on ``https://innioasis.app``:

1. Master JSON feed: ``https://innioasis.app/feeds/firmware-releases.json``
2. Master Atom/XML feed: ``https://innioasis.app/feeds/firmware-feed.xml``
3. Legacy backup feeds: ``https://innioasis.app/feeds/releases.json`` and
   ``https://innioasis.app/feeds/releases.xml``
4. Static HTML fallback page (for user browser failover):
   ``https://innioasis.app/firmware-list.html``

Parsed feed data is normalized into a single dictionary structure and cached
both in memory and on disk at ``cache_dir() / "innioasis_feed_cache.json"``.
"""

