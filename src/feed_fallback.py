def get_packages_from_feed(
    force_refresh: bool = False,
    session=None,
    feed: Optional[dict[str, Any]] = None,
) -> list[dict[str, Any]]:
    """Return the ``packages`` list from the fallback feed."""
    data = feed if feed is not None else fetch_fallback_feed(force_refresh=force_refresh, session=session)
    if not isinstance(data, dict):
        return []
    pkgs = data.get("packages")
    return list(pkgs) if isinstance(pkgs, list) else []
