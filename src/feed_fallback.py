FEED_XML_URL = "https://innioasis.app/feeds/firmware-feed.xml"
LEGACY_FEED_JSON_URL = "https://innioasis.app/feeds/releases.json"
LEGACY_FEED_XML_URL = "https://innioasis.app/feeds/releases.xml"
FIRMWARE_LIST_URL = "https://innioasis.app/firmware-list.html"

FEED_CACHE_FILENAME = "innioasis_feed_cache.json"
FEED_CACHE_TTL_SECONDS = RELEASE_CACHE_TTL_SECONDS
REQUEST_TIMEOUT = 10

_MEMORY_CACHE: Optional[dict[str, Any]] = None
_MEMORY_CACHE_TIME: float = 0.0


def cache_dir() -> Path:
    """Directory where the fallback feed cache is stored."""
    d = app_cache_dir()
    d.mkdir(parents=True, exist_ok=True)
    return d


def cache_path() -> Path:
    """Path to ``innioasis_feed_cache.json`` on disk."""
    return cache_dir() / FEED_CACHE_FILENAME


def clear_memory_cache() -> None:
    """Reset the in-memory feed cache (primarily for unit tests)."""
    global _MEMORY_CACHE, _MEMORY_CACHE_TIME
    _MEMORY_CACHE = None
    _MEMORY_CACHE_TIME = 0.0


def _local_tag(tag: str) -> str:
    """Strip XML namespace URI prefix ``{...}`` or prefix ``inni:``."""
    if not tag:
        return ""
    if "}" in tag:
        tag = tag.split("}", 1)[1]
    if ":" in tag:
        tag = tag.split(":", 1)[1]
    return tag.strip()


def _parse_bool(val: Any) -> bool:
    if isinstance(val, bool):
        return val
    return str(val or "").strip().lower() in ("1", "true", "yes")


def _normalize_asset_dict(asset: dict[str, Any]) -> Optional[dict[str, Any]]:
    if not isinstance(asset, dict):
        return None
    name = str(asset.get("name") or asset.get("title") or "").strip()
    url = str(
        asset.get("browser_download_url")
        or asset.get("url")
        or asset.get("href")
        or ""
    ).strip()
    if not name or not url:
        return None
    try:
        size = int(asset.get("size") or asset.get("length") or 0)
    except (TypeError, ValueError):
        size = 0
    return {
        "name": name,
        "size": size,
        "browser_download_url": url,
        "content_type": str(
            asset.get("content_type")
            or asset.get("type")
            or "application/zip"
        ).strip(),
    }


def _normalize_release_dict(rel: dict[str, Any], repo: str = "") -> Optional[dict[str, Any]]:
    if not isinstance(rel, dict):
        return None
    tag_name = str(rel.get("tag_name") or rel.get("tag") or "").strip()
    if not tag_name:
        return None
    raw_assets = rel.get("assets") or []
    assets = []
    if isinstance(raw_assets, list):
        for a in raw_assets:
            norm_a = _normalize_asset_dict(a)
            if norm_a:
                assets.append(norm_a)
    html_url = str(rel.get("html_url") or "").strip()
    if not html_url and repo:
        html_url = f"https://github.com/{repo}/releases/tag/{tag_name}"
    out: dict[str, Any] = {
        "tag_name": tag_name,
        "name": str(rel.get("name") or rel.get("release_name") or tag_name),
        "published_at": str(rel.get("published_at") or rel.get("created_at") or ""),
        "prerelease": _parse_bool(rel.get("prerelease", False)),
        "draft": _parse_bool(rel.get("draft", False)),
        "html_url": html_url,
        "body": str(rel.get("body") or ""),
        "assets": assets,
    }
    if rel.get("icon_url"):
        out["icon_url"] = str(rel.get("icon_url"))
    if rel.get("icon_dark_url"):
        out["icon_dark_url"] = str(rel.get("icon_dark_url"))
    return out


def _build_raw_releases_from_mirror_dict(mirror_repo: str, mirror_data: dict[str, Any]) -> list[dict[str, Any]]:
    """Synthesize GitHub-API-shaped ``raw_releases`` from a mirror's ``releases`` map
    when ``raw_releases`` is not explicitly provided."""
    existing_raw = mirror_data.get("raw_releases")
    if isinstance(existing_raw, list) and existing_raw:
        normalized = []
        for r in existing_raw:
            nr = _normalize_release_dict(r, mirror_repo)
            if nr:
                normalized.append(nr)
        if normalized:
            return normalized

    releases_map = mirror_data.get("releases")
    if not isinstance(releases_map, dict):
        return []

    synthesized: list[dict[str, Any]] = []
    for tag_key, rel_info in releases_map.items():
        if not isinstance(rel_info, dict):
            continue
        m_tag = str(rel_info.get("mirror_tag") or rel_info.get("original_tag") or tag_key).strip()
        if not m_tag:
            continue
        assets_list: list[dict[str, Any]] = []
        assets_map = rel_info.get("assets")
        if isinstance(assets_map, dict):
            for orig_name, asset_info in assets_map.items():
                if not isinstance(asset_info, dict):
                    continue
                mirror_orig_url = str(asset_info.get("mirror_original_url") or "").strip()
                orig_size = int(asset_info.get("original_size") or 0)
                if mirror_orig_url and orig_name:
                    assets_list.append({
                        "name": str(orig_name),
                        "size": orig_size,
                        "browser_download_url": mirror_orig_url,
                        "content_type": "application/zip",
                    })
                pkgs = asset_info.get("packages")
                if isinstance(pkgs, dict):
                    for _plat, pkg_info in pkgs.items():
                        if not isinstance(pkg_info, dict):
                            continue
                        p_name = str(pkg_info.get("name") or "").strip()
                        p_url = str(pkg_info.get("url") or "").strip()
                        p_size = int(pkg_info.get("size") or 0)
                        if p_name and p_url:
                            assets_list.append({
                                "name": p_name,
                                "size": p_size,
                                "browser_download_url": p_url,
                                "content_type": "application/zip",
                            })
        synthesized.append({
            "tag_name": m_tag,
            "name": str(rel_info.get("release_name") or m_tag),
            "published_at": str(rel_info.get("published_at") or ""),
            "prerelease": _parse_bool(rel_info.get("prerelease", False)),
            "draft": False,
            "html_url": f"https://github.com/{mirror_repo}/releases/tag/{m_tag}",
            "body": str(rel_info.get("body") or ""),
            "assets": assets_list,
        })
    return synthesized


def parse_feed_json(payload: str | bytes | dict[str, Any]) -> Optional[dict[str, Any]]:
    """Parse and normalize a JSON feed payload into the canonical fallback dict."""
    if isinstance(payload, (str, bytes)):
        text = payload.decode("utf-8", errors="ignore") if isinstance(payload, bytes) else payload
        text = text.lstrip("\ufeff").strip()
        if not text or text[:200].lower().startswith(("<!doctype html", "<html")):
            return None
        try:
            data = json.loads(text)
        except Exception as e:
            logger.debug("Failed to parse JSON feed: %s", e)
            return None
    elif isinstance(payload, dict):
        data = payload
    else:
        return None

    if not isinstance(data, dict):
        return None

    packages_raw = data.get("packages")
    packages: list[dict[str, Any]] = []
    if isinstance(packages_raw, list):
        for p in packages_raw:
            if isinstance(p, dict) and (p.get("name") or p.get("slug") or p.get("repo")):
                packages.append(dict(p))

    repos_out: dict[str, list[dict[str, Any]]] = {}
    raw_repos = data.get("repos")
    if isinstance(raw_repos, dict):
        for repo_key, repo_val in raw_repos.items():
            repo_name = str(repo_key or "").strip()
            if not repo_name:
                continue
            rel_list: list[Any] = []
            if isinstance(repo_val, list):
                rel_list = repo_val
            elif isinstance(repo_val, dict) and isinstance(repo_val.get("releases"), list):
                rel_list = repo_val["releases"]
            norm_rels = []
            for r in rel_list:
                nr = _normalize_release_dict(r, repo_name)
                if nr and not nr.get("draft"):
                    norm_rels.append(nr)
            repos_out[repo_name] = norm_rels

    mirrors_out: dict[str, dict[str, Any]] = {}
    raw_mirrors = data.get("mirrors")
    if isinstance(raw_mirrors, dict):
        for m_repo, m_val in raw_mirrors.items():
            m_name = str(m_repo or "").strip()
            if not m_name or not isinstance(m_val, dict):
                continue
            m_copy = dict(m_val)
            m_copy.setdefault("mirror_repo", m_name)
            m_copy["raw_releases"] = _build_raw_releases_from_mirror_dict(m_name, m_copy)
            mirrors_out[m_name] = m_copy

    app_updates_out: dict[str, list[dict[str, Any]]] = {}
    raw_updates = data.get("app_updates")
    if isinstance(raw_updates, dict):
        for u_repo, u_list in raw_updates.items():
            u_name = str(u_repo or "").strip()
            if not u_name or not isinstance(u_list, list):
                continue
            norm_u = []
            for r in u_list:
                nr = _normalize_release_dict(r, u_name)
                if nr and not nr.get("draft"):
                    norm_u.append(nr)
            app_updates_out[u_name] = norm_u

    # Also populate app_updates from repos_out if present there (e.g. legacy feeds/releases.json)
    for update_repo in ("y1-community/updater-ce-neo", "y1-community/innioasis-updater", "y1-community/Innioasis-Updater"):
        if update_repo not in app_updates_out:
            for k, v in repos_out.items():
                if k.lower() == update_repo.lower() and v:
                    app_updates_out[update_repo] = v
                    break

    if not packages and not repos_out and not mirrors_out and not app_updates_out:
        return None

    return {
        "schema_version": int(data.get("schema_version") or 1),
        "generated_at": str(data.get("generated_at") or ""),
        "manifest_url": str(data.get("manifest_url") or "https://innioasis.app/slidia_manifest.xml"),
        "firmware_list_url": str(data.get("firmware_list_url") or FIRMWARE_LIST_URL),
        "packages": packages,
        "repos": repos_out,
        "mirrors": mirrors_out,
        "app_updates": app_updates_out,
    }


def _find_child_text(elem: ET.Element, local_names: tuple[str, ...]) -> str:
    for child in elem:
        if _local_tag(child.tag) in local_names:
            return (child.text or "").strip()
    return ""


def parse_feed_xml(xml_text: str | bytes) -> Optional[dict[str, Any]]:
    """Parse ``firmware-feed.xml`` (Atom + ``inni:`` namespace) or legacy
    ``releases.xml`` into the exact same dictionary structure as
    ``firmware-releases.json``."""
    text = xml_text.decode("utf-8", errors="ignore") if isinstance(xml_text, bytes) else str(xml_text or "")
    text = text.lstrip("\ufeff").strip()
    if not text or text[:200].lower().startswith(("<!doctype html", "<html")):
        return None
    try:
        root = ET.fromstring(text)
    except ET.ParseError as e:
        logger.debug("Failed to parse XML feed: %s", e)
        return None

    root_tag = _local_tag(root.tag)

    # Case 1: Legacy <releases_backup> XML
    if root_tag == "releases_backup":
        generated_at = str(root.attrib.get("generated_at") or "")
        repos_out: dict[str, list[dict[str, Any]]] = {}
        for repo_el in root:
            if _local_tag(repo_el.tag) != "repository":
                continue
            repo_name = str(repo_el.attrib.get("name") or "").strip()
            if not repo_name:
                continue
            rel_list: list[dict[str, Any]] = []
            for rel_el in repo_el:
                if _local_tag(rel_el.tag) != "release":
                    continue
                tag_name = str(rel_el.attrib.get("tag_name") or "").strip()
                if not tag_name:
                    continue
                body = _find_child_text(rel_el, ("body",))
                assets: list[dict[str, Any]] = []
                for child in rel_el:
                    if _local_tag(child.tag) == "assets":
                        for a_el in child:
                            if _local_tag(a_el.tag) == "asset":
                                norm_a = _normalize_asset_dict(a_el.attrib)
                                if norm_a:
                                    assets.append(norm_a)
                    elif _local_tag(child.tag) == "asset":
                        norm_a = _normalize_asset_dict(child.attrib)
                        if norm_a:
                            assets.append(norm_a)
                rel_dict = _normalize_release_dict({
                    "tag_name": tag_name,
                    "name": rel_el.attrib.get("name") or tag_name,
                    "published_at": rel_el.attrib.get("published_at") or "",
                    "prerelease": _parse_bool(rel_el.attrib.get("prerelease", False)),
                    "draft": _parse_bool(rel_el.attrib.get("draft", False)),
                    "html_url": rel_el.attrib.get("html_url") or "",
                    "icon_url": rel_el.attrib.get("icon_url") or "",
                    "icon_dark_url": rel_el.attrib.get("icon_dark_url") or "",
                    "body": body,
                    "assets": assets,
                }, repo_name)
                if rel_dict:
                    rel_list.append(rel_dict)
            repos_out[repo_name] = rel_list
        return parse_feed_json({
            "schema_version": 1,
            "generated_at": generated_at,
            "repos": repos_out,
        })

    # Case 2: Atom <feed xmlns="http://www.w3.org/2005/Atom" xmlns:inni="https://innioasis.app/ns/firmware/1.0">
    if root_tag != "feed":
        return None

    generated_at = _find_child_text(root, ("updated", "generated_at"))
    packages: list[dict[str, Any]] = []
    repos_out = {}
    mirrors_out: dict[str, dict[str, Any]] = {}
    app_updates_out: dict[str, list[dict[str, Any]]] = {}

    known_update_repos = {
        "y1-community/updater-ce-neo",
        "y1-community/innioasis-updater",
    }

    def _ensure_mirror_struct(mirror_repo: str, source_repo: str = "", updated_at: str = "") -> dict[str, Any]:
        if mirror_repo not in mirrors_out:
            mirrors_out[mirror_repo] = {
                "version": 1,
                "source_repo": source_repo,
                "mirror_repo": mirror_repo,
                "updated_at": updated_at or generated_at,
                "releases": {},
                "raw_releases": [],
            }
        else:
            if source_repo and not mirrors_out[mirror_repo].get("source_repo"):
                mirrors_out[mirror_repo]["source_repo"] = source_repo
            if updated_at and not mirrors_out[mirror_repo].get("updated_at"):
                mirrors_out[mirror_repo]["updated_at"] = updated_at
        return mirrors_out[mirror_repo]

    def _parse_mirror_asset_el(ma_el: ET.Element, default_mirror_repo: str = "", default_tag: str = "") -> None:
        m_repo = str(
            ma_el.attrib.get("mirror_repo")
            or ma_el.attrib.get("repo")
            or default_mirror_repo
            or ""
        ).strip()
        orig_name = str(
            ma_el.attrib.get("name")
            or ma_el.attrib.get("original_asset")
            or ma_el.attrib.get("asset")
            or ""
        ).strip()
        tag = str(
            ma_el.attrib.get("tag")
            or ma_el.attrib.get("mirror_tag")
            or ma_el.attrib.get("original_tag")
            or default_tag
            or ""
        ).strip()
        if not m_repo or not tag or not orig_name:
            return
        m_struct = _ensure_mirror_struct(
            m_repo,
            source_repo=str(ma_el.attrib.get("source_repo") or ""),
        )
        rel_entry = m_struct["releases"].setdefault(tag, {
            "original_tag": str(ma_el.attrib.get("original_tag") or tag),
            "mirror_tag": str(ma_el.attrib.get("mirror_tag") or tag),
            "release_name": str(ma_el.attrib.get("release_name") or tag),
            "published_at": str(ma_el.attrib.get("published_at") or ""),
            "assets": {},
        })
        try:
            orig_size = int(ma_el.attrib.get("original_size") or ma_el.attrib.get("size") or 0)
        except (TypeError, ValueError):
            orig_size = 0
        pkgs_dict: dict[str, dict[str, Any]] = {}
        # Platform packages can be child elements or attributes on <inni:mirror_asset>
        for child in ma_el:
            ctag = _local_tag(child.tag)
            if ctag in ("package", "portable", "platform"):
                plat = str(child.attrib.get("platform") or child.attrib.get("os") or "").strip()
                p_url = str(child.attrib.get("url") or child.attrib.get("browser_download_url") or child.attrib.get("href") or "").strip()
                p_name = str(child.attrib.get("name") or "").strip()
                if not p_name and p_url:
                    p_name = p_url.rsplit("/", 1)[-1]
                try:
                    p_size = int(child.attrib.get("size") or 0)
                except (TypeError, ValueError):
                    p_size = 0
                if plat and p_url:
                    pkgs_dict[plat] = {"name": p_name, "url": p_url, "size": p_size}

        for plat_key in ("windows", "windows-arm64", "linux", "linux-arm64", "macos"):
            attr_prefix = plat_key.replace("-", "_")
            p_url = str(
                ma_el.attrib.get(f"{plat_key}_url")
                or ma_el.attrib.get(f"{attr_prefix}_url")
                or ma_el.attrib.get(plat_key)
                or ""
            ).strip()
            if p_url and plat_key not in pkgs_dict:
                p_name = str(
                    ma_el.attrib.get(f"{plat_key}_name")
                    or ma_el.attrib.get(f"{attr_prefix}_name")
                    or p_url.rsplit("/", 1)[-1]
                ).strip()
                try:
                    p_size = int(
                        ma_el.attrib.get(f"{plat_key}_size")
                        or ma_el.attrib.get(f"{attr_prefix}_size")
                        or 0
                    )
                except (TypeError, ValueError):
                    p_size = 0
                pkgs_dict[plat_key] = {"name": p_name, "url": p_url, "size": p_size}

        rel_entry["assets"][orig_name] = {
            "original_url": str(ma_el.attrib.get("original_url") or ""),
            "original_size": orig_size,
            "mirror_original_url": str(ma_el.attrib.get("mirror_original_url") or ""),
            "packages": pkgs_dict,
        }

    for child in root:
        ctag = _local_tag(child.tag)
        if ctag == "packages":
            for pkg_el in child:
                if _local_tag(pkg_el.tag) != "package":
                    continue
                pkg_dict: dict[str, Any] = dict(pkg_el.attrib)
                # Child text elements override or supply attributes if present
                for sub in pkg_el:
                    stag = _local_tag(sub.tag)
                    if stag and (sub.text or "").strip():
                        pkg_dict.setdefault(stag, (sub.text or "").strip())
                if "description" not in pkg_dict and (pkg_el.text or "").strip():
                    pkg_dict["description"] = (pkg_el.text or "").strip()
                if "do_not_keep_data" in pkg_dict:
                    pkg_dict["do_not_keep_data"] = _parse_bool(pkg_dict["do_not_keep_data"])
                if "derivative" in pkg_dict and str(pkg_dict["derivative"]).lower() in ("true", "false"):
                    pkg_dict["derivative"] = _parse_bool(pkg_dict["derivative"])
                packages.append(pkg_dict)

        elif ctag == "mirrors":
            for m_el in child:
                if _local_tag(m_el.tag) != "mirror":
                    continue
                m_repo = str(m_el.attrib.get("repo") or m_el.attrib.get("mirror_repo") or "").strip()
                if not m_repo:
                    continue
                m_struct = _ensure_mirror_struct(
                    m_repo,
                    source_repo=str(m_el.attrib.get("source_repo") or ""),
                    updated_at=str(m_el.attrib.get("updated_at") or ""),
                )
                # If <inni:mirror> embeds JSON or child <release> / <mirror_asset> elements
                for m_child in m_el:
                    m_ctag = _local_tag(m_child.tag)
                    if m_ctag == "mirror_asset":
                        _parse_mirror_asset_el(m_child, default_mirror_repo=m_repo)
                    elif m_ctag == "release":
                        r_tag = str(
                            m_child.attrib.get("tag")
                            or m_child.attrib.get("mirror_tag")
                            or m_child.attrib.get("original_tag")
                            or m_child.attrib.get("tag_name")
                            or ""
                        ).strip()
                        if not r_tag:
                            continue
                        rel_entry = m_struct["releases"].setdefault(r_tag, {
                            "original_tag": str(m_child.attrib.get("original_tag") or r_tag),
                            "mirror_tag": str(m_child.attrib.get("mirror_tag") or r_tag),
                            "release_name": str(m_child.attrib.get("release_name") or m_child.attrib.get("name") or r_tag),
                            "published_at": str(m_child.attrib.get("published_at") or ""),
                            "assets": {},
                        })
                        for r_sub in m_child:
                            r_stag = _local_tag(r_sub.tag)
                            if r_stag in ("mirror_asset", "asset"):
                                _parse_mirror_asset_el(r_sub, default_mirror_repo=m_repo, default_tag=r_tag)
                                # If it's a raw asset on a mirror release
                                if r_stag == "asset" and r_sub.attrib.get("browser_download_url"):
                                    pass
                        if not rel_entry["assets"]:
                            # Check if assets are inside an <assets> wrapper
                            for r_sub in m_child:
                                if _local_tag(r_sub.tag) == "assets":
                                    for a_sub in r_sub:
                                        if _local_tag(a_sub.tag) in ("mirror_asset", "asset"):
                                            _parse_mirror_asset_el(a_sub, default_mirror_repo=m_repo, default_tag=r_tag)

        elif ctag == "entry":
            repo = _find_child_text(child, ("repo", "repository", "source_repo"))
            tag_name = _find_child_text(child, ("tag_name", "tag"))
            release_name = _find_child_text(child, ("release_name", "title", "name"))
            published_at = _find_child_text(child, ("published_at", "published", "updated"))
            prerelease = _parse_bool(_find_child_text(child, ("prerelease",)))
            draft = _parse_bool(_find_child_text(child, ("draft",)))
            html_url = _find_child_text(child, ("html_url",))
            body = _find_child_text(child, ("body", "content", "summary"))
            icon_url = _find_child_text(child, ("icon_url",))
            icon_dark_url = _find_child_text(child, ("icon_dark_url",))
            entry_kind = _find_child_text(child, ("kind", "category", "type")).lower()

            assets: list[dict[str, Any]] = []
            for e_sub in child:
                estag = _local_tag(e_sub.tag)
                if estag == "link":
                    rel_attr = str(e_sub.attrib.get("rel") or "alternate").strip()
                    if rel_attr == "alternate" and not html_url:
                        html_url = str(e_sub.attrib.get("href") or "").strip()
                    elif rel_attr == "enclosure":
                        norm_a = _normalize_asset_dict(e_sub.attrib)
                        if norm_a:
                            assets.append(norm_a)
                elif estag == "asset":
                    norm_a = _normalize_asset_dict(e_sub.attrib)
                    if norm_a:
                        assets.append(norm_a)
                elif estag == "assets":
                    for a_el in e_sub:
                        if _local_tag(a_el.tag) == "asset":
                            norm_a = _normalize_asset_dict(a_el.attrib)
                            if norm_a:
                                assets.append(norm_a)
                elif estag == "category":
                    term = str(e_sub.attrib.get("term") or "").strip().lower()
                    if term and not entry_kind:
                        entry_kind = term
                elif estag == "mirror_asset":
                    # Find mirror_repo from attribute, or package portable_zips matching repo
                    m_repo = str(e_sub.attrib.get("mirror_repo") or e_sub.attrib.get("repo") or "").strip()
                    if not m_repo and repo:
                        for p in packages:
                            if str(p.get("repo") or "").lower() == repo.lower() and p.get("portable_zips"):
                                m_repo = str(p.get("portable_zips")).split(",")[0].strip()
                                break
                    if not m_repo and repo in mirrors_out:
                        m_repo = repo
                    _parse_mirror_asset_el(e_sub, default_mirror_repo=m_repo, default_tag=tag_name)

            if not repo and html_url and "github.com/" in html_url:
                parts = html_url.split("github.com/", 1)[1].split("/")
                if len(parts) >= 2:
                    repo = f"{parts[0]}/{parts[1]}"

            if not repo or not tag_name or draft:
                continue

            rel_obj = _normalize_release_dict({
                "tag_name": tag_name,
                "name": release_name or tag_name,
                "published_at": published_at,
                "prerelease": prerelease,
                "draft": draft,
                "html_url": html_url,
                "body": body,
                "icon_url": icon_url,
                "icon_dark_url": icon_dark_url,
                "assets": assets,
            }, repo)
            if not rel_obj:
                continue

            if entry_kind in ("app_update", "app_updates", "update") or repo.lower() in known_update_repos:
                app_updates_out.setdefault(repo, []).append(rel_obj)
            elif entry_kind == "mirror" or repo in mirrors_out:
                m_struct = _ensure_mirror_struct(repo)
                m_struct["raw_releases"].append(rel_obj)
            else:
                repos_out.setdefault(repo, []).append(rel_obj)

    for m_name, m_struct in mirrors_out.items():
        if not m_struct.get("raw_releases") and m_name in repos_out:
            m_struct["raw_releases"] = list(repos_out[m_name])
        m_struct["raw_releases"] = _build_raw_releases_from_mirror_dict(m_name, m_struct)

    if not packages and not repos_out and not mirrors_out and not app_updates_out:
        return None

    return {
        "schema_version": 1,
        "generated_at": generated_at,
        "manifest_url": "https://innioasis.app/slidia_manifest.xml",
        "firmware_list_url": FIRMWARE_LIST_URL,
        "packages": packages,
        "repos": repos_out,
        "mirrors": mirrors_out,
        "app_updates": app_updates_out,
    }


def _read_disk_cache(ignore_ttl: bool = False) -> Optional[dict[str, Any]]:
    path = cache_path()
    if not path.is_file():
        return None
    try:
        if not ignore_ttl and (time.time() - path.stat().st_mtime) >= FEED_CACHE_TTL_SECONDS:
            return None
        raw = json.loads(path.read_text(encoding="utf-8"))
        if isinstance(raw, dict):
            feed = raw.get("feed") if isinstance(raw.get("feed"), dict) else raw
            return parse_feed_json(feed)
    except Exception as e:
        logger.debug("Failed to read innioasis_feed_cache.json: %s", e)
    return None


def _write_disk_cache(feed: dict[str, Any]) -> None:
    path = cache_path()
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_name(path.name + ".tmp")
        tmp.write_text(
            json.dumps({"timestamp": time.time(), "feed": feed}, ensure_ascii=False),
            encoding="utf-8",
        )
        os.replace(tmp, path)
    except Exception as e:
        logger.debug("Failed to write innioasis_feed_cache.json: %s", e)


def _fetch_url_text(url: str, session=None, timeout: float = REQUEST_TIMEOUT) -> Optional[str]:
    headers = {
        "User-Agent": "InnioasisUpdater/3.0 (+https://innioasis.app)",
        "Cache-Control": "no-cache",
    }
    try:
        client = session if session is not None else requests_module()
        resp = client.get(url, headers=headers, timeout=timeout)
        status = getattr(resp, "status_code", 200)
        if status != 200:
            return None
        text = getattr(resp, "text", None)
        if text is None and hasattr(resp, "content"):
            text = resp.content.decode("utf-8", errors="ignore")
        return text
    except Exception as e:
        logger.debug("Feed fetch failed for %s: %s", url, e)
        return None


def fetch_fallback_feed(
    force_refresh: bool = False,
    session=None,
    timeout: float = REQUEST_TIMEOUT,
    allow_stale_cache: bool = True,
) -> Optional[dict[str, Any]]:
    """Fetch and parse ``firmware-releases.json``, falling back to
    ``firmware-feed.xml`` (and legacy ``releases.json`` / ``releases.xml``),
    with in-memory and disk caching in ``cache_dir() / "innioasis_feed_cache.json"``."""
    global _MEMORY_CACHE, _MEMORY_CACHE_TIME

    now = time.time()
    if (
        not force_refresh
        and _MEMORY_CACHE is not None
        and (now - _MEMORY_CACHE_TIME) < FEED_CACHE_TTL_SECONDS
    ):
        return _MEMORY_CACHE

    if not force_refresh:
        disk_cached = _read_disk_cache(ignore_ttl=False)
        if disk_cached is not None:
            _MEMORY_CACHE = disk_cached
            _MEMORY_CACHE_TIME = now
            return disk_cached

    # 1. Try primary JSON feed URLs (innioasis.app + GitHub raw fallback)
    json_urls: list[str] = []
    for u in (FEED_JSON_URL, *site_source_urls("feeds/firmware-releases.json")):
        if u and u not in json_urls:
            json_urls.append(u)

    for url in json_urls:
        text = _fetch_url_text(url, session=session, timeout=timeout)
        if text:
            parsed = parse_feed_json(text)
            if parsed is not None:
                _MEMORY_CACHE = parsed
                _MEMORY_CACHE_TIME = time.time()
                _write_disk_cache(parsed)
                return parsed

    # 2. Fall back to primary Atom/XML feed URLs (firmware-feed.xml)
    xml_urls: list[str] = []
    for u in (FEED_XML_URL, *site_source_urls("feeds/firmware-feed.xml")):
        if u and u not in xml_urls:
            xml_urls.append(u)

    for url in xml_urls:
        text = _fetch_url_text(url, session=session, timeout=timeout)
        if text:
            parsed = parse_feed_xml(text)
            if parsed is not None:
                _MEMORY_CACHE = parsed
                _MEMORY_CACHE_TIME = time.time()
                _write_disk_cache(parsed)
                return parsed

    # 3. Try legacy releases.json / releases.xml on innioasis.app
    for url in (LEGACY_FEED_JSON_URL, *site_source_urls("feeds/releases.json")):
        text = _fetch_url_text(url, session=session, timeout=timeout)
        if text:
            parsed = parse_feed_json(text)
            if parsed is not None:
                _MEMORY_CACHE = parsed
                _MEMORY_CACHE_TIME = time.time()
                _write_disk_cache(parsed)
                return parsed

    for url in (LEGACY_FEED_XML_URL, *site_source_urls("feeds/releases.xml")):
        text = _fetch_url_text(url, session=session, timeout=timeout)
        if text:
            parsed = parse_feed_xml(text)
            if parsed is not None:
                _MEMORY_CACHE = parsed
                _MEMORY_CACHE_TIME = time.time()
                _write_disk_cache(parsed)
                return parsed

    # 4. Stale disk cache if network is completely unreachable
    if allow_stale_cache:
        stale = _read_disk_cache(ignore_ttl=True)
        if stale is not None:
            _MEMORY_CACHE = stale
            _MEMORY_CACHE_TIME = time.time()
            return stale

    return None


def _case_insensitive_get(mapping: dict[str, Any], key: str) -> Any:
    if not isinstance(mapping, dict) or not key:
        return None
    if key in mapping:
        return mapping[key]
    target = key.strip().lower()
    for k, v in mapping.items():
        if str(k).strip().lower() == target:
            return v
    return None


def get_repo_releases_from_feed(
    repo: str,
    force_refresh: bool = False,
    session=None,
    feed: Optional[dict[str, Any]] = None,
) -> list[dict[str, Any]]:
    """Look up releases for ``repo`` in the ``innioasis.app`` static feed
    (checking ``repos[repo]``, ``mirrors[repo]["raw_releases"]``, and
    ``app_updates[repo]``)."""
    repo_clean = str(repo or "").strip().strip("/")
    if not repo_clean:
        return []
    data = feed if feed is not None else fetch_fallback_feed(force_refresh=force_refresh, session=session)
    if not isinstance(data, dict):
        return []

    repos_map = data.get("repos") or {}
    found = _case_insensitive_get(repos_map, repo_clean)
    if isinstance(found, list) and found:
        return list(found)

    mirrors_map = data.get("mirrors") or {}
    mirror_entry = _case_insensitive_get(mirrors_map, repo_clean)
    if isinstance(mirror_entry, dict):
        raw_rels = mirror_entry.get("raw_releases")
        if isinstance(raw_rels, list) and raw_rels:
            return list(raw_rels)

    updates_map = data.get("app_updates") or {}
    found_updates = _case_insensitive_get(updates_map, repo_clean)
    if isinstance(found_updates, list) and found_updates:
        return list(found_updates)

    return []


def get_mirror_from_feed(
    mirror_repo: str,
    force_refresh: bool = False,
    session=None,
    feed: Optional[dict[str, Any]] = None,
) -> Optional[dict[str, Any]]:
    """Return ``mirrors[mirror_repo]`` from the ``innioasis.app`` fallback feed."""
    repo_clean = str(mirror_repo or "").strip().strip("/")
    if not repo_clean:
        return None
    data = feed if feed is not None else fetch_fallback_feed(force_refresh=force_refresh, session=session)
    if not isinstance(data, dict):
        return None
    mirrors_map = data.get("mirrors") or {}
    found = _case_insensitive_get(mirrors_map, repo_clean)
    if isinstance(found, dict):
        return found
    return None


